export function getItemName(itemId, language = 'es') {
  const item = itemTranslations[itemId];
  if (item) return item[language] || item.es;
  // Fallback: convertir ID a nombre legible
  return itemId
    .split('-')
    .map(word => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
}

export function getPocketName(pocketKey, language = 'es') {
  const pocket = pocketTranslations[pocketKey];
  if (pocket) return pocket[language] || pocket.es;
  // Fallback: convertir key a nombre legible
  return pocketKey
    .split('_')
    .map(word => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
}
